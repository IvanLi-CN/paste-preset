import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { installIconVersion } from "./pwa-icon-contract.mjs";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = resolve(projectRoot, "public");
const pwaDir = resolve(publicDir, "pwa");
const background = [0xee, 0xf4, 0xff];

async function pixelsFor(name) {
  const { data, info } = await sharp(resolve(pwaDir, name))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  return { data, info };
}

async function assertMaskable(name, size) {
  const { data, info } = await pixelsFor(name);
  assert.equal(info.width, size, `${name} width`);
  assert.equal(info.height, size, `${name} height`);
  assert.equal(info.channels, 4, `${name} channels`);

  const foreground = [];
  for (let offset = 0; offset < data.length; offset += 4) {
    const alpha = data[offset + 3];
    assert.equal(alpha, 255, `${name} must be opaque`);
    const difference = Math.max(
      Math.abs(data[offset] - background[0]),
      Math.abs(data[offset + 1] - background[1]),
      Math.abs(data[offset + 2] - background[2]),
    );
    if (difference >= 16)
      foreground.push([(offset / 4) % size, Math.floor(offset / 4 / size)]);
  }

  assert.ok(foreground.length > 0, `${name} foreground`);
  const xs = foreground.map(([x]) => x);
  const ys = foreground.map(([, y]) => y);
  const ratio =
    Math.max(
      Math.max(...xs) - Math.min(...xs) + 1,
      Math.max(...ys) - Math.min(...ys) + 1,
    ) / size;
  assert.ok(
    ratio >= 0.58 && ratio <= 0.62,
    `${name} foreground ratio ${ratio.toFixed(3)}`,
  );

  const center = size / 2;
  const radius = size * 0.4;
  assert.ok(
    foreground.every(
      ([x, y]) => Math.hypot(x + 0.5 - center, y + 0.5 - center) <= radius,
    ),
    `${name} foreground escapes the 40% safe circle`,
  );
}

async function assertRegular(name, size) {
  const { data, info } = await pixelsFor(name);
  assert.equal(info.width, size, `${name} width`);
  assert.equal(info.height, size, `${name} height`);
  assert.ok(
    data.some((_, index) => index % 4 === 3 && data[index] < 16),
    `${name} keeps transparent corners`,
  );
}

function assertManifest() {
  const version = installIconVersion(projectRoot);
  const manifest = JSON.parse(
    readFileSync(resolve(publicDir, "manifest.webmanifest"), "utf8"),
  );
  assert.deepEqual(
    manifest.icons.map(({ src, sizes, type, purpose }) => ({
      src,
      sizes,
      type,
      purpose,
    })),
    [
      {
        src: `/pwa/icon-192.png?v=${version}`,
        sizes: "192x192",
        type: "image/png",
        purpose: "any",
      },
      {
        src: `/pwa/icon-512.png?v=${version}`,
        sizes: "512x512",
        type: "image/png",
        purpose: "any",
      },
      {
        src: `/pwa/icon-192-maskable.png?v=${version}`,
        sizes: "192x192",
        type: "image/png",
        purpose: "maskable",
      },
      {
        src: `/pwa/icon-512-maskable.png?v=${version}`,
        sizes: "512x512",
        type: "image/png",
        purpose: "maskable",
      },
    ],
    "manifest must keep distinct, content-versioned any and maskable resources",
  );
}

function assertBuildContract() {
  const index = readFileSync(resolve(projectRoot, "index.html"), "utf8");
  const viteConfig = readFileSync(
    resolve(projectRoot, "vite.config.ts"),
    "utf8",
  );
  assert.ok(
    index.includes("%INSTALL_ICON_VERSION%"),
    "HTML install links must be content-versioned",
  );
  assert.ok(
    viteConfig.includes("installIconVersion"),
    "Vite must derive the HTML icon version from generated bytes",
  );

  const distDir = resolve(projectRoot, "dist");
  assert.ok(
    existsSync(distDir),
    "build output is missing; run the PWA build before this checker",
  );
  const manifest = readFileSync(
    resolve(distDir, "manifest.webmanifest"),
    "utf8",
  );
  const builtManifest = JSON.parse(manifest);
  const sourceManifest = JSON.parse(
    readFileSync(resolve(publicDir, "manifest.webmanifest"), "utf8"),
  );
  assert.deepEqual(
    builtManifest.icons,
    sourceManifest.icons,
    "built manifest icon entries differ from the source contract",
  );
  const builtHtml = readFileSync(resolve(distDir, "index.html"), "utf8");
  assert.ok(
    builtHtml.includes(
      `apple-touch-icon.png?v=${installIconVersion(projectRoot)}`,
    ),
    "built Apple touch URL is stale",
  );
  const worker = readFileSync(resolve(distDir, "sw.js"), "utf8");
  const serviceWorkerSource = readFileSync(
    resolve(projectRoot, "scripts/sw-template.js"),
    "utf8",
  );
  assert.ok(
    serviceWorkerSource.includes("normalizeCoreUrl") &&
      serviceWorkerSource.includes('searchParams.delete("v")'),
    "service worker must normalize content-versioned icon URLs",
  );
  assert.ok(
    worker.includes("normalizeCoreUrl") &&
      worker.includes('searchParams.delete("v")'),
    "built service worker must normalize content-versioned icon URLs",
  );
  assert.ok(manifest.includes("?v="), "built manifest lost icon versioning");
  for (const name of [
    "apple-touch-icon.png",
    "icon-192.png",
    "icon-512.png",
    "icon-192-maskable.png",
    "icon-512-maskable.png",
  ]) {
    assert.ok(worker.includes(`pwa/${name}`), `Workbox precache omits ${name}`);
  }
}

async function main() {
  await assertRegular("icon-192.png", 192);
  await assertRegular("icon-512.png", 512);
  await assertMaskable("icon-192-maskable.png", 192);
  await assertMaskable("icon-512-maskable.png", 512);
  await assertMaskable("apple-touch-icon.png", 180);
  assert.notEqual(
    createHash("sha256")
      .update(readFileSync(resolve(pwaDir, "icon-512.png")))
      .digest("hex"),
    createHash("sha256")
      .update(readFileSync(resolve(pwaDir, "icon-512-maskable.png")))
      .digest("hex"),
    "regular and maskable icons must not share bytes",
  );
  assertManifest();
  assertBuildContract();
}

await main();
console.log("PWA asset contract passed.");
